export function cloneDemoEntities(): SpatialEntityRecord {
  return demoSpatialEntities.reduce<SpatialEntityRecord>((record, entity) => {
    record[entity.id] = {
      ...entity,
      position: [...entity.position],
      rotation: [...entity.rotation],
      scale: [...entity.scale],
      metadata: { ...entity.metadata }
    };
    return record;
  }, {} as SpatialEntityRecord);
}

export function getDemoEntity(id: SpatialEntityId): SpatialEntity | undefined {
  return demoSpatialEntities.find((entity) => entity.id === id);
}
